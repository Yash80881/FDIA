"""Run every research experiment and write tables + figures to ``results/``.

    python -m experiments.run_all_experiments            (python cli.py experiments)
    python -m experiments.run_all_experiments --quick    (fewer trees / rows)

Outputs: results/experiments_report.md, results/tables/*.csv, results/figures/*.png
Every number is computed here from the stored independent runs; nothing is typed in.
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
import tempfile
import time
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from config.settings import load_settings, resolve_path  # noqa: E402
from ml.common import load_bundle, write_json  # noqa: E402
from ml.preprocessing import load_splits  # noqa: E402
from ml.train_all import MODEL_FILES  # noqa: E402
from simulator.grid_model import GridModel  # noqa: E402
from experiments import evaluate_detection as ED, evaluate_localization as EL  # noqa: E402
from experiments import evaluate_attack_types as ET, benchmark_latency as BL  # noqa: E402

log = logging.getLogger("gridsentinel.experiments")


def md_table(df: pd.DataFrame, floatfmt: str = "{:.4f}") -> str:
    if df is None or df.empty:
        return "_no data_\n"
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out) + "\n"


def bar(df, x, y, hue, title, path, ylim=(0, 1.02)):
    piv = df.pivot_table(index=x, columns=hue, values=y, sort=False)
    ax = piv.plot(kind="bar", figsize=(10, 4.5), rot=20)
    ax.set_title(title)
    ax.set_ylim(*ylim)
    ax.grid(axis="y", alpha=.3)
    ax.legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(path, dpi=130)
    plt.close()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    args = ap.parse_args(argv)
    cfg = load_settings(None, args.set)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    res = resolve_path(cfg, "results")
    tables, figs = res / "tables", res / "figures"
    tables.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    n_trees = 60 if args.quick else 120
    phys_rows = 600 if args.quick else None
    t_start = time.perf_counter()

    splits, groups, local = load_splits(cfg)
    bus_numbers = GridModel().bus_numbers
    mdir = resolve_path(cfg, "models")
    det = load_bundle(mdir / MODEL_FILES["detection"])
    loc = load_bundle(mdir / MODEL_FILES["localization"])
    typ = load_bundle(mdir / MODEL_FILES["attack_type"])
    det_probs = {n: det["model"].predict_proba(s.X[det["features"]].to_numpy())[:, 1] for n, s in splits.items()}
    report = ["# GridSentinel AI - research experiments", "",
              f"Generated by `python -m experiments.run_all_experiments{' --quick' if args.quick else ''}`. "
              f"Experiment models use {n_trees} trees (the deployed models use the configured counts). "
              "All results are on independent simulation runs never used for fitting "
              "(test = 2 runs with base settings; stress runs change one condition each).", ""]

    log.info("1/7 detection feature ablation")
    abl = ED.ablation(cfg, splits, groups, n_trees)
    abl.to_csv(tables / "detection_ablation.csv", index=False)
    bar(abl[abl.split == "test"], "features", "f1", "split", "Detection F1 by feature group (test runs)",
        figs / "detection_ablation.png")
    piv = abl.pivot_table(index="features", columns="split", values="f1", sort=False).reset_index()
    report += ["## 1. Detection - feature-group ablation (F1)", "", md_table(piv),
               "Full metrics: `results/tables/detection_ablation.csv`.", ""]

    log.info("2/7 alternative models")
    alt = ED.alternative_models(cfg, splits, groups, n_trees)
    alt.to_csv(tables / "detection_models.csv", index=False)
    piv = alt.pivot_table(index="model", columns="split", values="f1", sort=False).reset_index()
    report += ["## 2. Random Forest vs alternative models (detection F1, full features)", "", md_table(piv), ""]
    bar(alt[alt.split == "test"].melt(id_vars=["model"], value_vars=["precision", "recall", "f1"]),
        "model", "value", "variable", "Detection on test runs: RF vs alternatives", figs / "detection_models.png")

    log.info("3/7 detection breakdowns")
    bd = ED.breakdowns(cfg, splits, det)
    write_json(tables / "detection_breakdowns.json", bd)
    report += ["## 3. Deployed detector - breakdowns (test runs)", "",
               "Recall by attack type: " + ", ".join(f"{k} {v:.3f}" for k, v in bd["by_attack_type"].items()), "",
               "Single- vs multi-bus recall: " + ", ".join(f"{k} {v:.3f}" for k, v in bd["single_vs_multi_bus_recall"].items()), "",
               "Recall by attack severity (noise-normalised magnitude):", "",
               md_table(pd.DataFrame([{"severity": k, **v} for k, v in bd["recall_by_severity"].items()])),
               "By operating scenario (load level):", "",
               md_table(pd.DataFrame([{"scenario": k, **v} for k, v in bd["by_scenario"].items()])),
               "Recall vs position inside an attack event: " +
               ", ".join(f"{k}: {v:.3f}" for k, v in bd["recall_by_attack_step"].items()), ""]

    log.info("4/7 AI vs physics")
    avp = ED.ai_vs_physics(cfg, splits, det, phys_rows)
    avp.to_csv(tables / "ai_vs_physics.csv", index=False)
    report += ["## 4. AI-only vs physics-only vs combined detection", "", md_table(avp),
               "Physics = WLS state estimation with chi-square (α = 0.01) and largest-normalised-residual (>3) tests, "
               "using each run's own sensor-noise model.", ""]
    bar(avp, "split", "f1", "method", "Detection F1: AI vs physics vs combined", figs / "ai_vs_physics.png")

    log.info("5/7 localisation experiments")
    with open(mdir / "metrics" / "localization.json") as fh:
        locm = json.load(fh)
    rows = []
    for regime, r in locm["regimes"].items():
        for split, m in r["splits"].items():
            rows.append({"regime": regime, "split": split,
                         "oracle micro-F1": m["oracle_attacked_snapshots"]["micro_f1"],
                         "oracle macro-F1": m["oracle_attacked_snapshots"]["macro_f1"],
                         "two-stage micro-F1": m["two_stage_all_snapshots"]["micro_f1"],
                         "two-stage macro-F1": m["two_stage_all_snapshots"]["macro_f1"]})
    reg = pd.DataFrame(rows)
    reg.to_csv(tables / "localization_regimes.csv", index=False)
    scope = EL.scope_comparison(cfg, splits, groups, local, det_probs, det["threshold"], bus_numbers, n_trees)
    scope.to_csv(tables / "localization_scope.csv", index=False)
    mo = EL.multioutput_baseline(cfg, splits, groups, det_probs, det["threshold"], bus_numbers, n_trees)
    mo.to_csv(tables / "localization_multioutput.csv", index=False)
    bc = EL.breakdown_by_bus_count(loc, splits, bus_numbers)
    bc.to_csv(tables / "localization_breakdown.csv", index=False)
    pl = EL.physics_localization_baseline(cfg, splits, bus_numbers, 300 if args.quick else 1000)
    report += ["## 5. Localisation", "",
               f"Deployed model: regime **{loc['regime']}**, feature scope **{loc['feature_scope']}** "
               "(selected on validation two-stage micro-F1).", "",
               "### 5a. Training regime (deployed configuration)", "", md_table(reg),
               "### 5b. Feature scope x regime", "", md_table(scope[scope.split == "test"]),
               "### 5c. Single multi-output Random Forest baseline", "", md_table(mo),
               "### 5d. Physics (LNR) localisation baseline on truly attacked test snapshots", "",
               md_table(pd.DataFrame([pl])),
               "### 5e. Deployed localiser by attack size and type (oracle, test runs)", "", md_table(bc), ""]
    f1 = next(r for r in locm["regimes"][loc["regime"]]["splits"]["test"]["oracle_attacked_snapshots"]["per_bus"])
    per_bus = pd.DataFrame(locm["regimes"][loc["regime"]]["splits"]["test"]["oracle_attacked_snapshots"]["per_bus"])
    ax = per_bus.plot(x="bus", y=["precision", "recall", "f1"], kind="bar", figsize=(12, 4))
    ax.set_title("Per-bus localisation (test runs, oracle)")
    ax.set_ylim(0, 1.02)
    plt.tight_layout()
    plt.savefig(figs / "localization_per_bus.png", dpi=130)
    plt.close()
    _ = f1

    log.info("6/7 attack types")
    ps = ET.per_split(typ, splits)
    ps.to_csv(tables / "attack_type_splits.csv", index=False)
    ta = ET.ablation(cfg, splits, groups, n_trees)
    ta.to_csv(tables / "attack_type_ablation.csv", index=False)
    report += ["## 6. Attack-type classification (truly attacked snapshots)", "", md_table(ps),
               "Feature ablation (test runs):", "", md_table(ta), ""]

    log.info("7/7 latency")
    lat = BL.inference_latency(cfg, 60 if args.quick else 200)
    thr = BL.simulator_throughput(cfg, 150 if args.quick else 400)
    with tempfile.TemporaryDirectory() as td:
        e2e = BL.end_to_end(cfg, Path(td) / "e2e.db", steps=30 if args.quick else 60, interval=0.5)
    write_json(tables / "latency.json", {"inference": lat, "simulator": thr, "end_to_end": e2e})
    lrows = [{"component": k, **v} for k, v in lat.items() if v]
    report += ["## 7. Latency, throughput and dropped measurements", "", md_table(pd.DataFrame(lrows), "{:.2f}"),
               f"Simulator (power flow + measurements + attacks, no I/O): {thr['steps_per_second']:.1f} steps/s "
               f"({thr['ms_per_step']:.1f} ms/step).", "",
               f"End-to-end real-time run ({e2e['steps']} steps at {e2e['interval_s']} s): processed "
               f"{e2e['processed']}, dropped {e2e['dropped']}, mean processing {e2e['mean_processing_ms']:.1f} ms "
               "per snapshot (AI + physics + alerting).", ""]
    report += ["---", f"Total experiment time: {time.perf_counter() - t_start:.0f} s."]
    (res / "experiments_report.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"Wrote {res / 'experiments_report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
